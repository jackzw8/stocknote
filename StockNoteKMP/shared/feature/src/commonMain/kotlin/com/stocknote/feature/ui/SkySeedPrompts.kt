package com.stocknote.feature.ui

/**
 * 看天看地 · 种子清单**提示词模板**（FR-SE-11 / 需求说明书附录 A·B）。
 *
 * ⚠️ 正文是需求文档的正式产物（老周用它去问 AI、AI 的返回要能被 [com.stocknote.core.io.SkySeedParser]
 * 解析）—— 改文案 = 改需求，别顺手改。
 * ⚠️ 模板与占位符替换集中在这里，**不在 UI 里拼字符串**（技术说明书 §7.5）。
 */
object SkySeedPrompts {

    /** 看天（宏观）提示词：`{{DATE}}` → 当前日期。 */
    fun sky(date: String): String = SKY_TEMPLATE.replace("{{DATE}}", date)

    /** 看地（个股）提示词：`{{DATE}}` / `{{NAME}}` / `{{CODE}}` / `{{MARKET}}`。 */
    fun earth(date: String, name: String, code: String, market: String): String =
        EARTH_TEMPLATE
            .replace("{{DATE}}", date)
            .replace("{{NAME}}", name)
            .replace("{{CODE}}", code)
            .replace("{{MARKET}}", market)

    /** 由 symbol 猜市场名（复制模板用）。 */
    fun marketOf(symbol: String): String = when {
        symbol.startsWith("hk", ignoreCase = true) -> "港股"
        symbol.startsWith("sh", ignoreCase = true) || symbol.startsWith("sz", ignoreCase = true) -> "A股"
        symbol.startsWith("us", ignoreCase = true) -> "美股"
        else -> "A股"
    }

    private val SKY_TEMPLATE = """
        |你是一名服务中国大陆投资者的宏观策略研究员。现在是 {{DATE}}。
        |
        |我要在个人投资笔记 App 里维护一张「宏观关注点清单」，用来记录我此刻对市场的判断。
        |请你帮我生成这份清单的**建议条目**。
        |
        |【背景】
        |- 我的持仓集中在 A 股 与 港股通中的港股。
        |- 清单是我自己用的，只关心**对未来 1~3 个月的市场有实质影响**的关键点，不要教科书式的全面。
        |
        |【输出要求 —— 严格遵守，否则我无法解析】
        |1. 输出**纯文本**，第一行固定为：SEED:SKY
        |2. 从第二行起，每行一条，格式严格为：
        |   序号|标题|档位|理由
        |   - 分隔符是英文竖线 |，标题中不要出现竖线
        |   - 序号从 1 开始连续递增
        |   - 档位只能是这三个词之一：悲观 / 中性 / 乐观
        |   - 标题 ≤ 16 个汉字，直击要害，不要写"XXX的影响"这种空标题
        |   - 理由 ≤ 30 个汉字，必须落在**最近三个月内的事实或数据**上，不要写废话
        |3. 最多 10 条；请按**对我投资的重要程度从高到低**排序（第 1 条最重要）。
        |4. 判断口径：**站在当前时点，这个因素对市场是利好(乐观) / 利空(悲观) / 中性**。
        |5. 不要输出多余的解释、前言、免责声明、markdown 表格或代码块围栏。
        |6. 请在最后一行用 # 开头补一句：# 信息截至 YYYY-MM-DD，只写这一行注释。
        |
        |【维度参考，不必每个都用，挑当下真正要紧的】
        |国内政策基调 / 货币与流动性（LPR、降准降息、社融）/ 财政力度 /
        |A股估值位置（沪深300 PE-PB 历史分位）/ 增量资金（两融、公募新发、保险入市）/
        |经济基本面（PMI、CPI/PPI、地产、出口）/ 人民币汇率与外资流向 /
        |美元利率与全球流动性（美联储路径、美债）/ 港股特有的南向资金与 AH 溢价 /
        |中美关系与地缘风险 / 行业监管政策
        |
        |现在开始输出。
    """.trimMargin()

    private val EARTH_TEMPLATE = """
        |你是一名资深个股研究员。现在是 {{DATE}}。
        |
        |我要在个人投资笔记 App 里维护一张「个股关注点清单」，用来记录我此刻对这只票的判断。
        |请你帮我生成这份清单的**建议条目**。
        |
        |【标的】{{NAME}}（{{CODE}}），市场：{{MARKET}}
        |
        |【输出要求 —— 严格遵守，否则我无法解析】
        |1. 输出**纯文本**，第一行固定为：SEED:EARTH|{{NAME}}|{{CODE}}
        |2. 从第二行起，每行一条，格式严格为：
        |   序号|标题|档位|理由
        |   - 分隔符是英文竖线 |，标题中不要出现竖线
        |   - 序号从 1 开始连续递增
        |   - 档位只能是这三个词之一：悲观 / 中性 / 乐观
        |   - 标题 ≤ 16 个汉字，写成**这条我看的是什么**（如"游戏新游流水"、"回购节奏"）
        |   - 理由 ≤ 30 个汉字，必须引用**最近一期财报、已公告事件或可核实的数字**，不要写"值得关注"这类空话
        |3. 最多 5 条；请按**对这只票最重要、最不确定、最需要持续跟踪**的程度从高到低排序。
        |4. 判断口径：**站在当前股价和已知信息上，这个因素对股价是利好(乐观) / 利空(悲观) / 中性**。
        |   —— 注意是"这个因素"的判断，不是给这只票整体评级。
        |5. 不要输出多余的解释、前言、免责声明、markdown 表格或代码块围栏。
        |6. 请在最后一行用 # 开头补一句：# 信息截至 YYYY-MM-DD，只写这一行注释。
        |
        |【维度参考，只挑这只票当下真正的关键矛盾】
        |主营业务的量价趋势（新游/新品/月活/订单）/ 新业务与 AI 相关进展与资本开支 /
        |最近一期财报的收入、利润、指引与超预期程度 / 估值相对自身历史与同业的位置 /
        |竞争格局变化 / 监管与政策 / 回购、分红、大股东增减持等资金面行为 /
        |港股还需考虑：南向资金、AH 溢价、海外流动性敏感度
        |
        |现在开始输出。
    """.trimMargin()
}
